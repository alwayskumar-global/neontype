/**
 * Converter contract tests on the five REAL screens (Requirement 17.2, 17.6, 17.9). All file reads
 * go through scripts/dc-io.mjs (the studio has no @types/node); tests never import from design/.
 */
import { describe, it, expect } from "vitest";
import { convertAll, convertAllToMap, loadConfig, listStudioFiles, readStudioText, readTree, readDesignAsset } from "../../../scripts/dc-io.mjs";
import { DS_COMPONENTS } from "../../../scripts/dc-convert-lib.mjs";
import { leafRules, parseCss, splitSelectors } from "./css-util.js";

const same = (a: string | Uint8Array | undefined, b: string | Uint8Array | undefined): boolean => {
  if (a === undefined || b === undefined) return false;
  if (typeof a === "string" || typeof b === "string") return a === b;
  return a.length === b.length && a.every((v, i) => v === b[i]);
};

describe("determinism (Requirement 17.2)", () => {
  it("converting every screen twice gives byte-identical output", () => {
    const a = convertAllToMap();
    const b = convertAllToMap();
    expect(Object.keys(a)).toEqual(Object.keys(b));
    for (const k of Object.keys(a)) expect(same(a[k], b[k]), k).toBe(true);
  });
  it("output files appear in a fixed order per screen: css, tsx, then assets", () => {
    for (const r of convertAll()) {
      const names = r.files.map((f) => f.path);
      expect(names[0]).toBe(`${r.slug}/${r.slug}.css`);
      expect(names[1]).toBe(`${r.slug}/${r.componentName}.tsx`);
      expect(names.slice(2)).toEqual([...names.slice(2)].sort());
    }
  });
  it("outputs are LF only, end with exactly one newline, and carry no tabs, dates or absolute paths", () => {
    for (const [path, content] of Object.entries(convertAllToMap())) {
      if (typeof content !== "string") continue;
      expect(content.includes("\r"), path).toBe(false);
      expect(content.endsWith("\n") && !content.endsWith("\n\n"), path).toBe(true);
      expect(content.includes("\t"), path).toBe(false);
      expect(content, path).not.toMatch(/\/Users\/|\/home\/|[A-Z]:\\\\|\b20\d\d-\d\d-\d\d\b/);
    }
  });
  it("the header holds only the source name and the input sha256", () => {
    for (const r of convertAll()) {
      const tsx = r.files.find((f) => f.path.endsWith(".tsx"));
      expect(typeof tsx?.content).toBe("string");
      expect(tsx?.content as string).toMatch(/^\/\/ GENERATED by scripts\/dc-convert\.mjs\./);
      expect(tsx?.content as string).toMatch(/\n\/\/ sha256: [0-9a-f]{64}\n/);
    }
  });
});

describe("staleness (Requirement 17.9)", () => {
  it("regenerating in memory equals the committed src/generated/, files and bytes", () => {
    const fresh = convertAllToMap();
    const committed = readTree("src/generated");
    expect(Object.keys(committed).sort()).toEqual(Object.keys(fresh).sort());
    for (const k of Object.keys(fresh)) expect(same(committed[k], fresh[k]), `${k} is stale: run pnpm --filter @studio/app dc:convert`).toBe(true);
  });
  it("copied assets are byte-for-byte the design asset", () => {
    const logo = readDesignAsset("assets/neontype-logo.png");
    const committed = readTree("src/generated");
    const copies = Object.keys(committed).filter((k) => k.endsWith("/assets/neontype-logo.png"));
    expect(copies.length).toBeGreaterThan(0);
    for (const k of copies) expect(same(committed[k], logo), k).toBe(true);
  });
  it("converts all five configured screens", () => {
    const slugs = convertAll().map((r) => r.slug);
    expect(slugs).toEqual(["studio-editor", "effects-library", "export-flow", "error-states", "landing-page"]);
  });
});

describe("static audit of generated/ and ds/ (Requirement 17.6)", () => {
  // Product code only: test files legitimately contain the forbidden strings they assert against.
  const files = [...listStudioFiles("src/generated", [".tsx", ".ts", ".css"]), ...listStudioFiles("src/ds", [".tsx", ".ts", ".css"])].filter((p) => !/\.test\.tsx?$/.test(p));
  it("audits exactly the product files (10 generated + 5 ds sources)", () => {
    expect(files.filter((p) => p.startsWith("src/generated/")).length).toBe(10);
    expect(files.filter((p) => p.startsWith("src/ds/")).sort()).toEqual([
      "src/ds/dc-runtime.ts",
      "src/ds/ds.css",
      "src/ds/helpers.ts",
      "src/ds/icons.ts",
      "src/ds/index.tsx",
    ]);
  });
  for (const path of files) {
    it(`${path}`, () => {
      const text = readStudioText(path);
      // No inline style markup or prop, no HTML sink, no script/style element.
      expect(text, "style attribute").not.toMatch(/\bstyle\s*=/);
      expect(text, "dangerouslySetInnerHTML").not.toMatch(/dangerouslySetInnerHTML\s*[=:]/);
      expect(text, "<script").not.toMatch(/<script/i);
      expect(text, "<style").not.toMatch(/<style/i);
      expect(text, "eval").not.toMatch(/\beval\s*\(|new Function\s*\(/);
      // No import / URL path that reaches design/ or the bundle. In TS/TSX these are import specifiers;
      // in CSS they are @import and url() targets (the header comment naming the source is not a path).
      const isCss = path.endsWith(".css");
      const specs = isCss
        ? [...text.matchAll(/@import\s+["']([^"']+)["']|url\(\s*["']?([^"')]+)["']?\s*\)/g)].map((m) => m[1] ?? m[2] ?? "")
        : [...text.matchAll(/(?:^|\n)\s*(?:import|export)\b[^;]*?\bfrom\s*["']([^"']+)["']|(?:^|\n)\s*import\s*["']([^"']+)["']|\bimport\(\s*["']([^"']+)["']\s*\)/g)].map((m) => m[1] ?? m[2] ?? m[3] ?? "");
      for (const s of specs) {
        expect(s, `import ${s}`).not.toMatch(/design\/|_ds|support\.js|\.dc\.html/);
        expect(s, `import ${s}`).not.toMatch(/^[a-z]+:\/\//i);
      }
      if (path.endsWith(".tsx") || path.endsWith(".ts")) expect(text, "remote URL").not.toMatch(/https?:\/\//);
    });
  }
});

describe("generated CSS is scoped (scoper check, Requirement 17.5)", () => {
  for (const r of convertAll()) {
    it(`${r.slug}.css`, () => {
      const css = r.files.find((f) => f.path.endsWith(".css"))?.content as string;
      const root = `dc-${r.slug}`;
      const rules = parseCss(css); // throws on unbalanced braces
      expect(rules.length).toBeGreaterThan(0);
      for (const rule of rules) {
        if (rule.prelude.startsWith("@keyframes")) {
          expect(rule.prelude.replace("@keyframes", "").trim().startsWith(`${root}-`), rule.prelude).toBe(true);
        }
      }
      for (const leaf of leafRules(rules)) {
        if (leaf.prelude.startsWith("@")) continue;
        for (const sel of splitSelectors(leaf.prelude)) {
          expect(sel.startsWith(`.${root}`) || sel.startsWith(`:where(.${root})`), `${r.slug}: ${sel}`).toBe(true);
          expect(sel, sel).not.toMatch(/(^|[\s>+~,(])(html|body|:root)(?![\w-])/);
        }
      }
    });
  }
  it("animation references use the prefixed keyframe names", () => {
    const eff = convertAll().find((r) => r.slug === "effects-library");
    expect(eff).toBeDefined();
    expect(Object.keys(eff?.keyframes ?? {}).length).toBe(10);
    const css = eff?.files.find((f) => f.path.endsWith(".css"))?.content as string;
    for (const [orig, prefixed] of Object.entries(eff?.keyframes ?? {})) {
      expect(prefixed).toBe(`dc-effects-library-${orig}`);
      expect(css).toContain(`@keyframes ${prefixed}`);
      expect(css).not.toMatch(new RegExp(`animation(-name)?:[^;}]*(?<![\\w-])${orig}(?![\\w-])`));
    }
  });
});

describe("per-file config rules (Requirement 17.4, owner-approved)", () => {
  const byslug = Object.fromEntries(convertAll().map((r) => [r.slug, r]));
  const text = (slug: string, ext: string): string => byslug[slug]?.files.find((f) => f.path.endsWith(ext))?.content as string;

  it("Landing Page: four design links become #studio with the optional onOpenStudio handler", () => {
    const tsx = text("landing-page", ".tsx");
    expect(tsx.match(/href="#studio"/g)).toHaveLength(4);
    expect(tsx.match(/onClick=\{asHandler\(get\(scope, "onOpenStudio"\)\)\}/g)).toHaveLength(4);
    expect(tsx).not.toContain("Studio Editor.dc.html");
    expect(byslug["landing-page"]?.bindings).toContain("onOpenStudio");
  });
  it("Error States: icon colour comes from a class per variant, no object-valued style", () => {
    const tsx = text("error-states", ".tsx");
    const css = text("error-states", ".css");
    expect(tsx).toContain('data-variant={asText(get(s1, "w.icon"))}');
    expect(css).toMatch(/\[data-variant="error"\]\s*\{\s*color: var\(--color-error\);\s*\}/);
    expect(css).toMatch(/\[data-variant="warning"\]\s*\{\s*color: var\(--color-warning\);\s*\}/);
    expect(tsx).not.toMatch(/iconStyle/);
  });
  it("the config file lists exactly the approved rules", () => {
    const cfg = loadConfig();
    const rules = Object.fromEntries(cfg.files.map((f) => [f.source, f]));
    expect(rules["Export Flow.dc.html"]?.omitIf).toEqual([]); // the revised design no longer has the Review bar
    expect(rules["Landing Page.dc.html"]?.replaceText).toHaveLength(1);
    expect(rules["Landing Page.dc.html"]?.replaceText[0]?.expect).toBe(4);
    expect(rules["Error States.dc.html"]?.replaceText).toHaveLength(2);
    expect(rules["Studio Editor.dc.html"]?.omitIf).toEqual([]);
    expect(cfg.forbid.length).toBeGreaterThanOrEqual(5);
  });
});

describe("what the generated modules expose", () => {
  it("only import design-system components that the port exports", () => {
    for (const path of listStudioFiles("src/generated", [".tsx"])) {
      const text = readStudioText(path);
      const m = /import \{ ([^}]+) \} from "\.\.\/\.\.\/ds\/index\.js";/.exec(text);
      if (!m) continue;
      for (const name of (m[1] ?? "").split(",").map((s) => s.trim())) expect(DS_COMPONENTS, `${path}: ${name}`).toContain(name);
    }
  });
  it("each screen exports BINDINGS (sorted, unique) and KEYFRAMES", () => {
    for (const r of convertAll()) {
      expect([...r.bindings]).toEqual([...new Set(r.bindings)].sort());
      const CONST = r.slug.toUpperCase().replace(/-/g, "_");
      const tsx = r.files.find((f) => f.path.endsWith(".tsx"))?.content as string;
      expect(tsx).toContain(`export const ${CONST}_BINDINGS`);
      expect(tsx).toContain(`export const ${CONST}_KEYFRAMES`);
    }
  });
  it("only the screens with a dc-import take a backdrop prop", () => {
    for (const r of convertAll()) {
      const tsx = r.files.find((f) => f.path.endsWith(".tsx"))?.content as string;
      const wantsBackdrop = r.slug === "effects-library" || r.slug === "export-flow";
      expect(/\{ data, backdrop \}/.test(tsx), r.slug).toBe(wantsBackdrop);
    }
  });
  it("the vendor runtime, the bundle script and the data script are dropped, never embedded", () => {
    for (const r of convertAll()) {
      expect(r.dropped).toContain("support.js");
      expect(r.dropped).toContain("data script");
    }
    for (const content of Object.values(convertAllToMap())) {
      if (typeof content === "string") expect(content).not.toMatch(/componentDidMount|setState|text\/x-dc|data-dc-script/);
    }
  });
});
